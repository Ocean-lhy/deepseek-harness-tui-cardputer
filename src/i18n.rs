//! Minimal i18n: English (default) and Chinese.
//!
//! Language is stored in `~/.dst/config.yml` as `language: en|zh|es|ja|de|it`
//! and can be changed from `/config`. User-facing interface text is translated
//! here; tool descriptions stay English, and the system prompt carries a
//! LANGUAGE section naming the selected language as the default answer
//! language (with an explicit user request always taking precedence, see
//! `language_name`/`language_native`).

use std::sync::RwLock;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Zh,
    Es,
    Ja,
    De,
    It,
}

static LANG: RwLock<Lang> = RwLock::new(Lang::En);

pub fn set(language: &str) {
    let code = language.trim().to_ascii_lowercase();
    let l = if code.starts_with("zh") {
        Lang::Zh
    } else if code.starts_with("es") {
        Lang::Es
    } else if code.starts_with("ja") {
        Lang::Ja
    } else if code.starts_with("de") {
        Lang::De
    } else if code.starts_with("it") {
        Lang::It
    } else {
        Lang::En
    };
    if let Ok(mut g) = LANG.write() {
        *g = l;
    }
}

pub fn lang() -> Lang {
    LANG.read().map(|g| *g).unwrap_or(Lang::En)
}

#[allow(dead_code)] // exposed for callers that persist the language code
pub fn code() -> &'static str {
    match lang() {
        Lang::En => "en",
        Lang::Zh => "zh",
        Lang::Es => "es",
        Lang::Ja => "ja",
        Lang::De => "de",
        Lang::It => "it",
    }
}

/// English name of the current UI language: the system prompt tells the model
/// which language to answer in, so the name has to be unambiguous.
pub fn language_name() -> &'static str {
    match lang() {
        Lang::En => "English",
        Lang::Zh => "Simplified Chinese",
        Lang::Es => "Spanish",
        Lang::Ja => "Japanese",
        Lang::De => "German",
        Lang::It => "Italian",
    }
}

/// Native spelling of the current UI language (what the user sees in /config).
pub fn language_native() -> &'static str {
    match lang() {
        Lang::En => "English",
        Lang::Zh => "简体中文",
        Lang::Es => "Español",
        Lang::Ja => "日本語",
        Lang::De => "Deutsch",
        Lang::It => "Italiano",
    }
}

